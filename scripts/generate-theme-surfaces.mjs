/** Convert legacy fixed surface colours into scoped dark-theme equivalents.
 * Original light stylesheet and anatomical SVG/3D colours remain untouched.
 * Run after adding legacy component CSS; review the generated diff.
 */
import fs from 'node:fs';
import postcss from 'postcss';
const files=['globals.css','activity-upgrade.css','atlas/atlas-upgrade.css','site-upgrade.css'];
const output=postcss.root();
const dark='html[data-theme="dark"]';
function rgb(hex){let h=hex.slice(1);if(h.length===3||h.length===4)h=h.split('').map(c=>c+c).join('');return [0,2,4].map(i=>parseInt(h.slice(i,i+2),16)/255);}
function luminance(hex){return rgb(hex).reduce((s,c,i)=>s+c*[.2126,.7152,.0722][i],0);}
function walk(node,parent){
 if(node.type==='atrule') { if(/print/.test(node.params)||node.name==='keyframes')return; const n=node.clone({nodes:[]});node.each?.(c=>walk(c,n));if(n.nodes?.length)parent.append(n);return; }
 if(node.type!=='rule'||node.selector.includes(':root'))return;
 // Explicit light/dark canvas backgrounds are separate user controls, not site theme.
 const preserve=/atlas-background-|atlas-stage$|kidney-figure/.test(node.selector);
 const changes=[];
 let accent=false;
 node.each(d=>{
  if(d.type!=='decl')return;
  const prop=d.prop;let value=d.value;
  if((prop==='background'||prop==='background-color')&&!preserve){
   value=value.replaceAll('var(--ink)','var(--solid)').replaceAll('var(--green)','var(--solid-green)');
   if(/var\(--lime\)|#dfff7a/i.test(value)){
    accent=/studio-hero-visual|round-play|featured-play|video-play|new-tag|button-lime|header-practice|skip-link|button|dominant-cell|activity-kind|input:checked|workspace-summary>a|>span/.test(node.selector);
    if(!accent)value=value.replace(/var\(--lime\)|#dfff7a/gi,'var(--accent-panel)');
   }
   value=value.replace(/(?<![-\w])white\b|#[0-9a-f]{3,8}\b/gi,h=>{
    if(h==='white'||/^#(?:fff|ffffff)$/i.test(h))return 'var(--white)';
    if(/^#dfff7a$/i.test(h))return h;
    if(h.length===5||h.length===9)return luminance(h)>.65?'var(--surface-overlay)':h;
    return luminance(h)>.64?'var(--surface-raised)':h;
   });
  }else if(prop==='color'){
   value=value.replace(/#[0-9a-f]{3,8}\b/gi,h=>{
    const l=luminance(h);if(l>.62)return h;
    if(/error|incorrect|urgent/.test(node.selector))return 'var(--warning-text)';
    return l<.23?'var(--ink)':'var(--muted)';
   });
  }else if(/^(border|outline)/.test(prop)){
   value=value.replace(/#[0-9a-f]{3,8}\b/g,'var(--line)');
  }
  if(value!==d.value || /^(background|background-color|color)$/.test(prop))changes.push(d.clone({value}));
 });
 if(accent)changes.push(postcss.decl({prop:'color',value:'#152e26'}));
 if(!changes.length)return;
 const selectors=node.selectors.map(s=>s.trim()==='html'?dark:s.trim()==='body'?dark+' body':dark+' '+s.trim());
 parent.append(postcss.rule({selector:selectors.join(',\n'),nodes:changes}));
}
for(const file of files)postcss.parse(fs.readFileSync('app/'+file,'utf8')).each(n=>walk(n,output));
fs.writeFileSync('app/theme-surfaces.css','/* Generated by scripts/generate-theme-surfaces.mjs. Scoped overrides preserve light mode. */\n'+output.toString());
